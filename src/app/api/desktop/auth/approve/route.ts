import { and, eq } from "drizzle-orm";
import { NextResponse } from "next/server";
import { tr } from "@/i18n/server-text";
import { auth } from "@/lib/auth";
import { deviceLoginBrand } from "@/lib/auth/device-brand";
import { db } from "@/lib/db";
import { desktopDevices, desktopLicenses, members } from "@/lib/db/schema";
import { generateDeviceToken } from "@/lib/desktop-auth";
import { resolveDeviceCallback } from "@/lib/device-login";

/**
 * POST /api/desktop/auth/approve
 *
 * Called from the browser when the user clicks "Godkend forbindelse"
 * on the desktop authorization page.
 *
 * Body: { code: string, organizationId?: string, redirectUri?: string }
 *
 * Returns: { redirectUrl: "timetrack://auth/callback?token=JWT&org=ORG_ID" }
 * The scheme follows `redirectUri` if it is on the app-scheme allowlist,
 * otherwise the instance brand (timewren:// or timetrack://).
 */
export async function POST(request: Request) {
  try {
    // 1. Verify the user is authenticated via Better-Auth session cookie
    const session = await auth.api.getSession({ headers: request.headers });
    if (!session?.user?.id) {
      return NextResponse.json(
        { error: await tr("serverErrors", "api.notAuthorized") },
        { status: 401 },
      );
    }

    const { id: userId, name: userName, email: userEmail } = session.user;

    // 2. Parse request body
    const body = (await request.json()) as {
      code?: string;
      organizationId?: string;
      redirectUri?: string;
    };

    if (!body.code || typeof body.code !== "string") {
      return NextResponse.json(
        { error: await tr("serverErrors", "api.desktop.deviceCodeMissing") },
        { status: 400 },
      );
    }

    const { code, organizationId } = body;

    // 3. Validate organization membership if an org was selected
    if (organizationId) {
      const membership = await db.query.members.findFirst({
        where: and(
          eq(members.userId, userId),
          eq(members.organizationId, organizationId),
        ),
      });

      if (!membership) {
        return NextResponse.json(
          { error: await tr("serverErrors", "api.notMemberOfChosenOrg") },
          { status: 403 },
        );
      }
    }

    // 4. Use the device code as a machine identifier for device registration
    //    The code is a unique string generated by the desktop app.
    const machineId = code;

    // 5. Check user's desktop license for tier and device limits
    const license = await db.query.desktopLicenses.findFirst({
      where: and(
        eq(desktopLicenses.userId, userId),
        eq(desktopLicenses.isActive, true),
      ),
    });

    const tier = license?.tier ?? "free";

    // 6. Find or create device registration
    let device = await db.query.desktopDevices.findFirst({
      where: and(
        eq(desktopDevices.userId, userId),
        eq(desktopDevices.machineId, machineId),
      ),
    });

    if (!device) {
      // Check device limit if license exists
      if (license) {
        const deviceCount = await db
          .select({ id: desktopDevices.id })
          .from(desktopDevices)
          .where(eq(desktopDevices.userId, userId));

        if (deviceCount.length >= license.maxDevices) {
          return NextResponse.json(
            {
              error: await tr("serverErrors", "api.desktop.maxDevices", {
                max: license.maxDevices,
              }),
            },
            { status: 403 },
          );
        }
      }

      const [newDevice] = await db
        .insert(desktopDevices)
        .values({
          userId,
          machineId,
          deviceName: null,
          os: null,
        })
        .returning();
      device = newDevice;
    }

    // 7. Generate a 90-day device JWT
    const token = await generateDeviceToken(userId, device.id, tier);

    // 8. Build the deep link redirect URL
    const params = new URLSearchParams({ token });
    if (organizationId) {
      params.set("org", organizationId);
    }
    // Include user info so the desktop app can display it immediately
    params.set("email", userEmail);
    params.set("name", userName);
    params.set("tier", tier);

    const callback = resolveDeviceCallback({
      redirectUri: body.redirectUri,
      brand: deviceLoginBrand(request),
    });
    const redirectUrl = `${callback}?${params.toString()}`;

    return NextResponse.json({ redirectUrl });
  } catch (error) {
    console.error("[Desktop Auth Approve] Error:", error);
    return NextResponse.json(
      { error: await tr("serverErrors", "api.approvalFailed") },
      { status: 500 },
    );
  }
}
