"use client";

import { ArrowRight, Loader2 } from "lucide-react";
import { useState } from "react";
import { toast } from "sonner";
import { useSafeTranslations } from "@/components/ui/use-safe-translations";
import daDesktop from "@/i18n/messages/da/desktop.json";
import { DESKTOP_LIFETIME_PRICE } from "@/lib/config";
import { trpc } from "@/providers/trpc-provider";

/**
 * Buy flow for the one-time Desktop Livstid license (see DESKTOP_LIFETIME_PRICE).
 *
 * Requires no account — collects an email, creates a Stripe one-time checkout
 * via trpc.desktop.createLifetimeCheckout, and redirects to Stripe. The license
 * key is generated by the Stripe webhook and emailed to the buyer.
 */
export function DesktopBuyButton({
  className = "",
  label,
}: {
  className?: string;
  label?: string;
}) {
  const t = useSafeTranslations("desktop", daDesktop);
  const buttonLabel =
    label ?? t("buy.label", { price: DESKTOP_LIFETIME_PRICE });
  const [open, setOpen] = useState(false);
  const [email, setEmail] = useState("");

  const checkout = trpc.desktop.createLifetimeCheckout.useMutation({
    onSuccess: ({ url }) => {
      window.location.href = url;
    },
    onError: (err) => {
      toast.error(err.message || t("buy.failed"));
    },
  });

  if (!open) {
    return (
      <button type="button" onClick={() => setOpen(true)} className={className}>
        {buttonLabel}
        <ArrowRight className="h-4 w-4" />
      </button>
    );
  }

  return (
    <form
      onSubmit={(e) => {
        e.preventDefault();
        checkout.mutate({ email });
      }}
      className="flex w-full flex-col gap-2"
    >
      <input
        type="email"
        required
        // biome-ignore lint/a11y/noAutofocus: focus the field the user just opened
        autoFocus
        value={email}
        onChange={(e) => setEmail(e.target.value)}
        placeholder={t("buy.emailPlaceholder")}
        className="w-full rounded-xl border border-slate-300 px-4 py-3 text-sm text-slate-900 outline-none focus:border-brand-500"
      />
      <button type="submit" disabled={checkout.isPending} className={className}>
        {checkout.isPending ? (
          <Loader2 className="h-4 w-4 animate-spin" />
        ) : (
          <>
            {t("buy.continue")}
            <ArrowRight className="h-4 w-4" />
          </>
        )}
      </button>
      <p className="text-center text-xs text-slate-400">{t("buy.keyNote")}</p>
    </form>
  );
}
